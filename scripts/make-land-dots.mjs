// Builds src/land-dots.js: evenly spaced points on land, for the dotted globe.
// Land outlines are Natural Earth 1:110m (public domain) via the world-atlas package.
//
//   npm i --no-save topojson-client
//   curl -o land-110m.json https://cdn.jsdelivr.net/npm/world-atlas@2/land-110m.json
//   node scripts/make-land-dots.mjs land-110m.json
//
// Output: latitude/longitude pairs ×100 as little-endian int16, base64 encoded (about 40 KB).

import { readFileSync, writeFileSync } from "node:fs";
import { feature } from "topojson-client";

const SPACING = 1.25; // degrees between dots
const source = process.argv[2] ?? "land-110m.json";
const topology = JSON.parse(readFileSync(source, "utf8"));
const land = feature(topology, topology.objects.land);
const polygons = land.features.flatMap((f) => (f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates));

/** Ray casting on one ring, in plain longitude/latitude. */
function inRing([x, y], ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

const onLand = (point) => polygons.some(([outer, ...holes]) => inRing(point, outer) && !holes.some((hole) => inRing(point, hole)));

const values = [];
for (let lat = -90 + SPACING / 2; lat < 90; lat += SPACING) {
  const count = Math.max(1, Math.round((360 * Math.cos((lat * Math.PI) / 180)) / SPACING));
  for (let i = 0; i < count; i++) {
    const lon = -180 + (360 * (i + 0.5)) / count;
    if (onLand([lon, lat])) values.push(Math.round(lat * 100), Math.round(lon * 100));
  }
}

const bytes = Buffer.from(new Int16Array(values).buffer);
writeFileSync(
  new URL("../src/land-dots.js", import.meta.url),
  `// Generated by scripts/make-land-dots.mjs from Natural Earth (public domain). ${values.length / 2} dots.\n` +
    `export const LAND_DOTS = "${bytes.toString("base64")}";\n`,
);
console.log(`${values.length / 2} dots, ${bytes.length} bytes`);
